import { describe, expect, it } from "bun:test";
import { processTraces } from "./traces";
import fs from "fs";
import path from "path";

describe("Traces processor - GCode parser", () => {
  it("parses older FlatCAM format without spaces between coordinates", () => {
    const gcode = `
G21
G90
G00 Z2.0000
G00 X10.0000Y20.0000
G01 Z0.0000
G01 X15.0000Y25.0000
G01 X20.0000Y30.0000
G00 Z2.0000
`;
    const traces = processTraces(gcode);
    expect(traces.length).toBe(1);
    expect(traces[0].length).toBe(3);
    expect(traces[0][0]).toEqual({ enabled: true, x: 10, y: 20 });
    expect(traces[0][1]).toEqual({ enabled: true, x: 15, y: 25 });
    expect(traces[0][2]).toEqual({ enabled: true, x: 20, y: 30 });
  });

  it("parses new FlatCAM Evo v1.0 format with spaces between coordinates and feedrates", () => {
    const gcode = `
(G-code generated by FlatCAM Evo v1.0)
G21
G90
G94
G01 F120.00
G00 Z2.0000
M03
G01 F120.00
G00 X3.3634 Y5.5801
G01 F60.00
G01 Z0.0000
G01 F120.00
G01 X3.3732 Y5.7054
G01 X3.4001 Y5.8120
G00 Z2.0000
`;
    const traces = processTraces(gcode);
    expect(traces.length).toBe(1);
    expect(traces[0].length).toBe(3);
    expect(traces[0][0]).toEqual({ enabled: true, x: 3.3634, y: 5.5801 });
    expect(traces[0][1]).toEqual({ enabled: true, x: 3.3732, y: 5.7054 });
    expect(traces[0][2]).toEqual({ enabled: true, x: 3.4001, y: 5.8120 });
  });

  it("handles negative cut depths (Z <= 0)", () => {
    const gcode = `
G00 Z2.0000
G00 X1.0 Y2.0
G01 Z-0.0500
G01 X3.0 Y4.0
G00 Z2.0000
`;
    const traces = processTraces(gcode);
    expect(traces.length).toBe(1);
    expect(traces[0].length).toBe(2);
    expect(traces[0][0]).toEqual({ enabled: true, x: 1, y: 2 });
    expect(traces[0][1]).toEqual({ enabled: true, x: 3, y: 4 });
  });

  it("merges contiguous traces that connect end-to-start", () => {
    const gcode = `
G00 X10.0 Y10.0
G01 Z0.0
G01 X20.0 Y20.0
G00 Z2.0
G00 X20.0 Y20.0
G01 Z0.0
G01 X30.0 Y30.0
G00 Z2.0
`;
    const traces = processTraces(gcode);
    expect(traces.length).toBe(1);
    expect(traces[0].length).toBe(3);
    expect(traces[0][0]).toEqual({ enabled: true, x: 10, y: 10 });
    expect(traces[0][1]).toEqual({ enabled: true, x: 20, y: 20 });
    expect(traces[0][2]).toEqual({ enabled: true, x: 30, y: 30 });
  });

  it("successfully parses all FlatCAM Evo homesensors gcode files from Project Outputs", () => {
    const dir = path.resolve(__dirname, "../../../../data/homesensors/Project Outputs for homesensors");
    const files = [
      "traces_top.gcode",
      "traces_bottom.gcode",
      "traces_profile.gcode",
      "silkscreen_top.gcode",
      "silkscreen_bottom.gcode",
      "soldermask_top.gcode",
      "soldermask_bottom.gcode",
    ];

    for (const f of files) {
      const filePath = path.join(dir, f);
      expect(fs.existsSync(filePath)).toBe(true);
      const content = fs.readFileSync(filePath, "utf-8");
      const traces = processTraces(content);
      expect(traces.length).toBeGreaterThan(0);
      expect(traces.every(t => t.length > 0)).toBe(true);
    }
  });
});
